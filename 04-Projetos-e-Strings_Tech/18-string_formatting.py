#Manipulação de Strings (ou Tratamento de Strings)

#upper( ): Transforma tudo em MAIÚSCULO
#lower( ): Tranforma tudo em minúsculo
#title( ): Deixa a Primeira Letra De Cada Palavra maiúscula (ótimo para nomes)
#capitalize( ): Apenas a Primeira letra da frase fica maiúscula

nome = "Fundação bradesco"

print(nome.upper())
print(nome.lower())
print(nome.title())
print(nome.capitalize())